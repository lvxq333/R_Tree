import 'dotenv/config';
import { spawnSync } from 'node:child_process';
import { readFileSync, existsSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
const checkpoint = path.resolve(process.argv[2] || '');
if (!checkpoint.includes(`${path.sep}.local${path.sep}recovery${path.sep}`)) throw new Error('请指定本项目 .local/recovery 下的完整检查点路径');
const manifest = JSON.parse(readFileSync(path.join(checkpoint, 'manifest.json'), 'utf8'));
for (const [file, hash] of Object.entries(manifest.files)) if (createHash('sha256').update(readFileSync(path.join(checkpoint, file))).digest('hex') !== hash) throw new Error(`校验失败：${file}`);
const pg = process.env.PG_BIN_DIR || '/opt/homebrew/opt/postgresql@16/bin';
const url = new URL(process.env.DATABASE_URL);
const target = `skilltree_recovery_${Date.now()}`;
const env = { ...process.env, PGHOST: url.hostname, PGPORT: url.port || '5432', PGUSER: decodeURIComponent(url.username), PGPASSWORD: decodeURIComponent(url.password) };
const run = (binary, args) => { const r = spawnSync(binary, args, { env, encoding: 'utf8' }); if (r.status !== 0) throw new Error(r.stderr || String(r.error)); return r.stdout; };
run(path.join(pg, 'createdb'), [target]);
run(path.join(pg, 'pg_restore'), ['--exit-on-error', '--no-owner', '--no-acl', '--dbname', target, path.join(checkpoint, 'database.dump')]);
const count = run(path.join(pg, 'psql'), ['--dbname', target, '-tAc', "SELECT count(*) FROM pg_tables WHERE schemaname='public'"]).trim();
const source = path.join(checkpoint, 'restored-source');
if (existsSync(source)) throw new Error('源码恢复目录已存在，不覆盖');
mkdirSync(source);
run('tar', ['-xzf', path.join(checkpoint, 'source.tar.gz'), '-C', source]);
console.log(`恢复演练成功：数据库 ${target}，public 表 ${count} 张；源码 ${source}。未修改当前数据库或当前代码。\n正式回退可启动恢复源码并将 DATABASE_URL 指向此恢复库；.env 需从本机现有配置复制。`);
